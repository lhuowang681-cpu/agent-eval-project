import { exec } from 'node:child_process';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';
import { promisify } from 'node:util';

import { app } from 'electron';

import { tripyoyoCliShimDir } from '@/const/dir';
import { createLogger } from '@/utils/logger';

import { ControllerModule, IpcMethod } from './index';
import RemoteServerConfigCtr from './RemoteServerConfigCtr';

const logger = createLogger('controllers:CliCtr');

const execAsync = promisify(exec);

function normalizeServerUrl(url: string): string {
  return url.replace(/\/$/, '');
}

/**
 * Runs the bundled tripyoyo CLI as the current desktop user against the current
 * desktop server.
 *
 * The CLI resolves its server/token from (in order) `TRIPYOYO_SERVER` / `TRIPYOYO_JWT`
 * env → `~/.tripyoyo/settings.json` → official default. When the agent runs `lh …`
 * via execScript, none of those env vars are set, so the CLI falls back to whatever
 * the user configured in their own terminal (often a stale localhost) and fails.
 * We inject the desktop session's token + server here so agent-invoked CLI commands
 * transparently act as the logged-in desktop user — mirroring LobeHub's CliCtr.
 *
 * ShellCommandCtr routes `lh`/`yoyo`/`tripyoyo`-prefixed execScript commands here.
 */
export default class CliCtr extends ControllerModule {
  static override readonly groupName = 'cli';

  @IpcMethod()
  async runCliCommand(args: string): Promise<{ exitCode: number; stderr: string; stdout: string }> {
    // Invoke the launcher generated by ensureTripyoyoCliShim (ELECTRON_RUN_AS_NODE
    // wrapper) by absolute path — no dependency on it being resolvable via PATH.
    const cmd = process.platform === 'win32' ? 'tripyoyo.cmd' : 'tripyoyo';
    const wrapperPath = join(tripyoyoCliShimDir, cmd);

    // Fail fast with an actionable message instead of letting execAsync surface a
    // bare "No such file or directory" — which leaves the agent unable to tell the
    // user how to fix it. The shim goes missing when the CLI bundle wasn't built
    // (dev: `apps/cli/dist/index.js` absent, so ensureTripyoyoCliShim no-ops) or
    // when a packaged build's beforePack didn't copy `tripyoyo-cli.js`.
    if (!existsSync(wrapperPath)) {
      const hint = app.isPackaged
        ? 'the CLI bundle was not copied into Resources/bin by beforePack — rebuild the installer'
        : 'in dev, run `bun --cwd apps/cli build` (or `pnpm dev:desktop`, which builds it automatically) and restart the app';
      logger.error(`tripyoyo CLI shim not found at ${wrapperPath}: ${hint}`);
      return {
        exitCode: 1,
        stderr: `tripyoyo CLI is unavailable — shim missing at ${wrapperPath}. ${hint}.`,
        stdout: '',
      };
    }

    const env = { ...process.env };

    const remoteCtr = this.app.getController(RemoteServerConfigCtr);
    if (remoteCtr) {
      const [token, serverUrl] = await Promise.all([
        remoteCtr.getAccessToken(),
        remoteCtr.getRemoteServerUrl(),
      ]);

      if (token && serverUrl) {
        env.TRIPYOYO_JWT = token;
        env.TRIPYOYO_SERVER = normalizeServerUrl(serverUrl);
        logger.debug('Injected TRIPYOYO_JWT / TRIPYOYO_SERVER for CLI command');
      }
    }

    try {
      // `args` is the shell-string tail of the execScript command (e.g.
      // `skill create -d "hello world"`); running it through the shell keeps the
      // original quoting/tokenization intact.
      const { stdout, stderr } = await execAsync(`"${wrapperPath}" ${args}`, {
        env,
        timeout: 15_000,
      });
      return { exitCode: 0, stderr, stdout };
    } catch (error: any) {
      return {
        exitCode: error.code ?? 1,
        stderr: error.stderr ?? '',
        stdout: error.stdout ?? String(error.message),
      };
    }
  }
}

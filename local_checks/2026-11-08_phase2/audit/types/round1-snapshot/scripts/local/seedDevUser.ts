#!/usr/bin/env tsx
/**
 * Seed the offline dev user.
 *
 * The offline setup authenticates via the development bypass: a request carrying
 * `lobe-auth-dev-backend-api: 1` is accepted as `process.env.MOCK_DEV_USER_ID`
 * (packages/openapi/src/middleware/auth.ts:51, src/libs/trpc/lambda/context.ts:98,
 * src/app/(backend)/middleware/auth/index.ts:41 — all guarded by NODE_ENV === 'development').
 *
 * That id must exist in `users`, otherwise every downstream model call fails on a
 * foreign key. This script creates it, idempotently.
 *
 * Usage:  bun run tsx scripts/local/seedDevUser.ts
 *         bun run tsx scripts/local/seedDevUser.ts --force   # overwrite existing row
 *
 * See PLAN.md §4.8 step 8.
 */
// MUST be first: db-adaptor reads DATABASE_URL / KEY_VAULTS_SECRET at import time and
// throws when they are missing. Import order is preserved, so this side-effect import
// populates process.env before the database module is evaluated.
import 'dotenv/config';

import { eq, sql } from 'drizzle-orm';

import { getServerDB } from '../../packages/database/src/core/db-adaptor';
import { users } from '../../packages/database/src/schemas';

const USER_ID = process.env.MOCK_DEV_USER_ID;
const force = process.argv.includes('--force');

const fail = (message: string): never => {
  console.error(`\n❌ ${message}\n`);
  process.exit(1);
};

const main = async () => {
  if (process.env.NODE_ENV === 'production') {
    fail('Refusing to run with NODE_ENV=production. This script is for local dev only.');
  }

  if (!USER_ID) {
    fail(
      'MOCK_DEV_USER_ID is not set.\n' +
        '   Copy .env.offline.example to .env first — the dev auth bypass resolves to that id.',
    );
  }

  if (!process.env.DATABASE_URL) {
    fail('DATABASE_URL is not set. Start Postgres and copy .env.offline.example to .env.');
  }

  const db = await getServerDB();

  const existing = await db.query.users.findFirst({ where: eq(users.id, USER_ID!) });

  if (existing && !force) {
    console.info(`✅ dev user already exists: ${USER_ID} (${existing.email ?? 'no email'})`);
    console.info('   Pass --force to overwrite the user row.');
    // Still (re)seed RBAC — it is idempotent and the user row existing says nothing
    // about whether roles/permissions were ever bootstrapped.
    await seedRbac(db);
    return;
  }

  const row = {
    avatar: null,
    email: 'offline-dev@localhost',
    emailVerified: true,
    fullName: 'Offline Dev User',
    id: USER_ID!,
    isOnboarded: true,
    username: 'offline-dev',
  };

  if (existing) {
    await db.update(users).set(row).where(eq(users.id, USER_ID!));
    console.info(`✅ dev user updated: ${USER_ID}`);
  } else {
    await db.insert(users).values(row);
    console.info(`✅ dev user created: ${USER_ID}`);
  }

  // ---- RBAC bootstrap ------------------------------------------------------
  // The migrations create rbac_roles / rbac_permissions / rbac_user_roles but seed
  // none of them, so on a fresh database every permission-gated /api/v1 endpoint is
  // denied. Without this the public REST API is unusable out of the box.
  await seedRbac(db);

  console.info('\nVerify with:');
  console.info(
    '  curl -H "lobe-auth-dev-backend-api: 1" http://localhost:3010/api/v1/users/me\n',
  );
};

const seedRbac = async (db: any) => {
  // RBAC_PERMISSIONS lives in the const package's rbac module, not its root export.
  const { RBAC_PERMISSIONS } = await import('../../packages/const/src/rbac');

  const values = [...new Set(Object.values(RBAC_PERMISSIONS) as string[])];
  console.info(`\n[rbac] 权限定义 ${values.length} 条`);

  // Use the ORM rather than raw SQL: `id` is generated by a Drizzle $defaultFn, so a
  // plain INSERT hits a not-null violation on the column.
  const { permissions, rolePermissions, roles, userRoles } = await import(
    '../../packages/database/src/schemas/rbac'
  );

  await db
    .insert(permissions)
    .values(
      values.map((code) => ({
        category: code.split(':')[0], // `agent:read:all` → `agent`
        code,
        description: 'offline dev seed',
        isActive: true,
        name: code,
      })),
    )
    .onConflictDoNothing();

  const allPerms = await db.select({ id: permissions.id }).from(permissions);
  console.info(`[rbac] rbac_permissions 现有 ${allPerms.length} 条`);

  await db
    .insert(roles)
    .values({
      description: 'offline dev seed',
      displayName: 'Administrator',
      isActive: true,
      isSystem: true,
      name: 'admin',
    })
    .onConflictDoNothing();

  const [adminRole] = await db.select({ id: roles.id }).from(roles).where(eq(roles.name, 'admin'));

  await db
    .insert(rolePermissions)
    .values(allPerms.map((p: any) => ({ permissionId: p.id, roleId: adminRole.id })))
    .onConflictDoNothing();

  await db
    .insert(userRoles)
    .values({ roleId: adminRole.id, userId: USER_ID! })
    .onConflictDoNothing();

  const granted = await db.select().from(userRoles).where(eq(userRoles.userId, USER_ID!));
  console.info(`[rbac] admin 角色已授予（role_id=${adminRole.id}），该用户 user_roles=${granted.length}`);
};

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error('\n❌ seedDevUser failed:', error);
    process.exit(1);
  });

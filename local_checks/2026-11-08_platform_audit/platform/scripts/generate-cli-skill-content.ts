/**
 * Generates apps/cli/src/generated/skillContent.ts from packages/builtin-skills/src/tripyoyo.
 *
 * apps/cli is published standalone as @ctrip/tripyoyo-cli and deliberately does not
 * depend on @lobechat/* packages at runtime (avoids pulling in the heavy
 * @lobechat/types dependency graph — same reasoning as apps/desktop/src/main). This
 * script runs from the repo root, which has access to both packages/builtin-skills
 * and apps/cli, and bakes the reference content into a plain, dependency-free
 * generated TS module that apps/cli's `install` command reads at runtime.
 *
 * Run: bun scripts/generate-cli-skill-content.ts
 * Regenerate whenever packages/builtin-skills/src/tripyoyo/** changes.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

import { TripYoYoSkill } from '../packages/builtin-skills/src/tripyoyo';

const OUTPUT_PATH = join(import.meta.dirname, '../apps/cli/src/generated/skillContent.ts');

const moduleRow = (path: string, content: string) => {
  const name = path.replace('references/', '');
  const firstLine = content.split('\n')[0] ?? '';
  const description = firstLine.replace(/^#\s*`?lh \S+\s*-\s*/, '').trim();
  return `| \`lh ${name}\` | ${description || name} |`;
};

const moduleRows = Object.entries(TripYoYoSkill.resources)
  .map(([path, resource]) => moduleRow(path, resource.content))
  .join('\n');

const skillMd = `---
name: tripyoyo
description: ${TripYoYoSkill.description.replaceAll('\n', ' ')}
---

# TripYoYo CLI (\`lh\`)

Manage the TripYoYo platform via the \`lh\` CLI (aliases: \`tripyoyo\`, \`yoyo\`). Run commands with the
Bash tool — the CLI must already be authenticated (\`lh login\`); if a command fails with
\`UNAUTHORIZED\`, tell the user to run \`lh login\`.

## Available Modules

| Module | Description |
| --- | --- |
${moduleRows}

## Usage Pattern

1. Read \`references/<module>.md\` for the module's detailed command syntax before running it
2. Use \`--json\` on \`list\`/query commands for machine-readable output — mutating commands (install,
   publish, update, etc.) print a short confirmation instead and do not accept \`--json\`
3. Use \`lh <module> --help\` for full command-line help
4. Use \`--yes\` to skip confirmation prompts on destructive operations

## Examples

\`\`\`bash
lh kb list
lh message search "deployment issue"
lh market skill list -q data --sort installCount
lh market skill install <identifier>
lh gen image "a sunset over mountains" -m dall-e-3
lh agent run -a <agentId> -p "Summarize today's tasks"
\`\`\`
`;

const referenceFiles: Record<string, string> = {};
for (const [path, resource] of Object.entries(TripYoYoSkill.resources)) {
  const name = path.replace('references/', '');
  referenceFiles[`${name}.md`] = resource.content;
}

const output = `// AUTO-GENERATED by scripts/generate-cli-skill-content.ts — do not edit by hand.
// Source of truth: packages/builtin-skills/src/tripyoyo/**
// Regenerate with: bun scripts/generate-cli-skill-content.ts

export const skillMd = ${JSON.stringify(skillMd)};

export const referenceFiles: Record<string, string> = ${JSON.stringify(referenceFiles, null, 2)};
`;

mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
writeFileSync(OUTPUT_PATH, output);
console.log(`Generated ${OUTPUT_PATH}`);
